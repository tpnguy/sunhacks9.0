#!/bin/bash
# Runs on the EC2 box (as root, via systemd ExecStartPre and push.sh).
# Writes /opt/dubstudio/env from SSM Parameter Store /dubstudio/* (SecureStrings decrypted
# with the instance role). Never prints values.
set -euo pipefail
ENV_FILE=/opt/dubstudio/env
REGION=$(cat /opt/dubstudio/region 2>/dev/null || echo us-west-2)
umask 077
tmp=$(mktemp)
trap 'rm -f "$tmp" "$tmp.out"' EXIT

if ! aws ssm get-parameters-by-path --region "$REGION" --path /dubstudio/ --with-decryption \
     --query 'Parameters[].[Name,Value]' --output text > "$tmp.out" 2>/dev/null; then
  echo "fetch-env: SSM unreachable; keeping existing $ENV_FILE" >&2
  exit 0
fi

{
  echo "# generated by fetch-env.sh from SSM /dubstudio/* at $(date -Is)"
  echo "AWS_REGION=$REGION"
  while IFS=$'\t' read -r name value; do
    [ -n "$name" ] || continue
    key=${name##*/}
    [ "$key" = AWS_REGION ] && continue
    printf '%s=%s\n' "$key" "$value"
  done < "$tmp.out"
} > "$tmp"

install -m 0600 -o root -g root "$tmp" "$ENV_FILE"
echo "fetch-env: wrote $(grep -c '=' "$ENV_FILE") vars to $ENV_FILE"
